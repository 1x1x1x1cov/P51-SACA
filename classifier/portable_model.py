"""
Pure-Python copy of the trained logistic regression, for devices without numpy/pandas/scikit-learn
(the Android app runs SACA inside the phone's WebView with Pyodide, which has no scikit-learn build).

    python -m classifier.portable_model        # retrain from dataset_v2 and write dataset_v2/saca_v2_model.json

The JSON holds the CountVectorizer vocabulary and stop words and the model's coefficients. PortablePipeline
gives the same answers as the scikit-learn pipeline (tests/test_portable_model.py checks every held-out row),
and exposes the few attributes LogisticRegressionClassifier uses: named_steps["vectorizer"].vocabulary_,
build_analyzer(), predict() and predict_proba().
"""
import json
import math
import os
import re
import unicodedata

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL_PATH = os.path.join(HERE, "dataset_v2", "saca_v2_model.json")
FORMAT = 1


def _strip_accents_unicode(s):
    # Same as sklearn.feature_extraction.text.strip_accents_unicode
    try:
        s.encode("ASCII", errors="strict")
        return s
    except UnicodeEncodeError:
        normalized = unicodedata.normalize("NFKD", s)
        return "".join(c for c in normalized if not unicodedata.combining(c))


class PortableVectorizer:
    def __init__(self, vocabulary, stop_words, token_pattern):
        self.vocabulary_ = vocabulary
        self.stop_words = frozenset(stop_words)
        self._token = re.compile(token_pattern)

    def build_analyzer(self):
        def analyze(doc):
            doc = _strip_accents_unicode(doc.lower())
            return [t for t in self._token.findall(doc) if t not in self.stop_words]
        return analyze

    def transform_one(self, doc):
        counts = {}
        for t in self.build_analyzer()(doc):
            j = self.vocabulary_.get(t)
            if j is not None:
                counts[j] = counts.get(j, 0) + 1
        return counts


class PortableLogisticRegression:
    def __init__(self, coef, intercept):
        self.coef_ = coef            # one row per class, one column per vocabulary index
        self.intercept_ = intercept

    def proba_one(self, counts):
        z = [b + sum(row[j] * c for j, c in counts.items()) for row, b in zip(self.coef_, self.intercept_)]
        top = max(z)
        e = [math.exp(v - top) for v in z]
        total = sum(e)
        return [v / total for v in e]


class PortablePipeline:
    def __init__(self, vectorizer, classifier):
        self.named_steps = {"vectorizer": vectorizer, "classifier": classifier}

    def predict_proba(self, docs):
        v, c = self.named_steps["vectorizer"], self.named_steps["classifier"]
        return [c.proba_one(v.transform_one(d)) for d in docs]

    def predict(self, docs):
        return [max(range(len(p)), key=p.__getitem__) for p in self.predict_proba(docs)]


class PortableLabelEncoder:
    def __init__(self, classes):
        self.classes_ = list(classes)

    def inverse_transform(self, encoded):
        return [self.classes_[int(i)] for i in encoded]


def load(path=MODEL_PATH):
    with open(path, encoding="utf-8") as f:
        m = json.load(f)
    if m.get("format") != FORMAT:
        raise ValueError(f"Unsupported model file format: {m.get('format')}")
    vec = PortableVectorizer(m["vocabulary"], m["stop_words"], m["token_pattern"])
    clf = PortableLogisticRegression(m["coef"], m["intercept"])
    return PortablePipeline(vec, clf), PortableLabelEncoder(m["classes"])


def export(classifier, path=MODEL_PATH):
    """Write a trained LogisticRegressionClassifier (scikit-learn) to the portable JSON format."""
    vec = classifier.pipeline.named_steps["vectorizer"]
    lr = classifier.pipeline.named_steps["classifier"]
    if vec.ngram_range != (1, 1) or not vec.lowercase or vec.strip_accents != "unicode" or vec.analyzer != "word":
        raise ValueError("The portable model only supports the word unigram CountVectorizer SACA uses.")
    if lr.coef_.shape[0] != len(lr.classes_):
        raise ValueError("Expected a multinomial (softmax) model with one row of coefficients per class.")
    model = {
        "format": FORMAT,
        "note": "Generated by classifier/portable_model.py from dataset_v2/saca_v2_train.csv. Do not edit.",
        "classes": [str(c) for c in classifier.label_encoder.classes_],
        "token_pattern": vec.token_pattern,
        "stop_words": sorted(vec.get_stop_words() or []),
        "vocabulary": {k: int(v) for k, v in sorted(vec.vocabulary_.items())},
        "coef": [[float(x) for x in row] for row in lr.coef_],
        "intercept": [float(x) for x in lr.intercept_],
    }
    with open(path, "w", encoding="utf-8") as f:
        json.dump(model, f, separators=(",", ":"))
    return path


if __name__ == "__main__":
    from classifier.logistic_regression import LogisticRegressionClassifier

    clf = LogisticRegressionClassifier()
    clf.train()
    print("wrote", export(clf))
